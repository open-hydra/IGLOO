#!/usr/bin/env bash
# Build the campaign's workloads under $IGLOO_PERF_ROOT/case/<name>/ from the shipped tree ($IGLOO_PERF_ROOT/src).
#   make-workloads.sh [name ...]     (default: khrt-stress vie-plait-dense box-4fam)
#
# Each workload holds INPUT/ (a dereferenced copy, or generated), input.ini (the source's, with timing = on in
# [IGLOO-General]), check.py (the committed workloads' own oracle), category.txt (the tests/ category its check
# expects to sit in), recipe.txt (what it was built from) and md5.txt (every other file). Idempotent: a workload
# whose recipe is unchanged and whose files still match md5.txt is left alone. Run it from a job (the box writes
# about 1.5 GB), never while another job reads the workloads.
#   khrt-stress      tests/breakup/khrt-stress: the output-bound workload (scatter records, the root merge)
#   vie-plait-dense  tests/standard/vie-plait-dense: the compute-bound workload at gas order 2
#   box-4fam         generated: IGLOO_BOX_CELLS (default "300 100 100") cubic cells, four families, gas order 2,
#                    source and Eulerian output, no particle output (the reduction volume and the memory per rank)
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
W=${W:-}
source "$HERE/_igloo_common.sh"
T=$SRC/tests
read -r NX NY NZ <<< "${IGLOO_BOX_CELLS:-300 100 100}"
mkdir -p "$CASE"

md5_of () { md5sum < "$1" | cut -d' ' -f1; }

# recipe <name>: the text that determines the workload's bytes
recipe () {
  local f
  case $1 in
    khrt-stress|vie-plait-dense)
      local src; src=$(source_of "$1")
      echo "copy tests/$src timing=on"
      for f in "$T/$src/input.ini" "$T/$src/check.py" "$T/$src/INPUT"/*; do
        echo "$(md5_of "$f") ${f#$T/}"
      done ;;
    box-4fam)
      echo "make_box_case.py --nx $NX --ny $NY --nz $NZ --families 4; properties.dat = tests/common;" \
           "input.ini = tests/standard/drag-stokes with gas-order=2 out-file=ALL out-traj=off out-scatter=off timing=on"
      for f in "$T/tools/make_box_case.py" "$T/common/properties.dat" "$T/standard/drag-stokes/input.ini"; do
        echo "$(md5_of "$f") ${f#$T/}"
      done ;;
    *) echo "unknown workload $1" >&2; return 1 ;;
  esac
}
source_of () { case $1 in khrt-stress) echo breakup/khrt-stress ;; vie-plait-dense) echo standard/vie-plait-dense ;; esac; }

build () {
  local name=$1 tmp=$CASE/.$1.tmp src
  rm -rf "$tmp"; mkdir -p "$tmp"
  case $name in
    khrt-stress|vie-plait-dense)
      src=$(source_of "$name")
      cp -rL "$T/$src/INPUT" "$tmp/INPUT"
      cp "$T/$src/input.ini" "$tmp/input.ini"
      cp "$T/$src/check.py" "$tmp/check.py"
      echo "${src%%/*}" > "$tmp/category.txt" ;;
    box-4fam)
      python3 -B "$T/tools/make_box_case.py" "$tmp/INPUT" --nx "$NX" --ny "$NY" --nz "$NZ" --families 4
      cp "$T/common/properties.dat" "$tmp/INPUT/properties.dat"
      { echo "; box-4fam: ${NX} x ${NY} x ${NZ} cubic cells, four families, gas order 2, source and Eulerian output,"
        echo "; no particle output; drag-stokes's models and tolerances (generated by make-workloads.sh)"
        grep -v '^ *;' "$T/standard/drag-stokes/input.ini"; } > "$tmp/input.ini"
      igloo_ini_set "$tmp/input.ini" gas-order=2 out-file=ALL out-traj=off out-scatter=off
      echo generated > "$tmp/category.txt" ;;
  esac
  igloo_ini_set "$tmp/input.ini" timing=on
  recipe "$name" > "$tmp/recipe.txt"
  (cd "$tmp" && find . -type f ! -name md5.txt | sed 's#^\./##' | LC_ALL=C sort | xargs md5sum > md5.txt)
  rm -rf "$CASE/$name.old"
  [ -d "$CASE/$name" ] && mv "$CASE/$name" "$CASE/$name.old"
  mv "$tmp" "$CASE/$name"
  rm -rf "$CASE/$name.old"
}

for name in ${@:-khrt-stress vie-plait-dense box-4fam}; do
  t0=$(date +%s)
  if [ -f "$CASE/$name/recipe.txt" ] && [ "$(recipe "$name")" = "$(cat "$CASE/$name/recipe.txt")" ] \
     && (cd "$CASE/$name" && md5sum -c --quiet md5.txt > /dev/null 2>&1); then
    state=unchanged
  else
    build "$name"; state=built
  fi
  echo "WORKLOAD $name md5=$(md5sum < "$CASE/$name/md5.txt" | cut -c1-12) $state" \
       "files=$(wc -l < "$CASE/$name/md5.txt") bytes=$(du -sbL "$CASE/$name" | cut -f1) s=$(( $(date +%s) - t0 ))"
done
